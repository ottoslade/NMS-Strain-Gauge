/**
* @brief  Function implementing the mainTask thread.
* @param  argument: Not used
* @retval None
*/
void mainTask(void *argument)
{
  for (;;)
  {
    if (!xSemaphoreTake(open_bootloader_running, pdMS_TO_TICKS(1000)))
    {
      OPENBL_FLASH_JumpToAddress((uint32_t)FLASH_START_ADDRESS);
    }
  }
}

/**
* @brief  Function implementing the stOpenBootTask thread.
* @param  argument: Not used
* @retval None
*/
void stOpenBootTask(void *argument)
{
  OpenBootloader_Init();
  for (;;)
  {
    OpenBootloader_ProtocolDetection();
  }
}

/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  HAL_Init();
  SystemClock_Config();

  MX_GPIO_Init();
  MX_CAN1_Init();

  /* Create starting tasks for FreeRTOS and bootloader */
  open_bootloader_running = xSemaphoreCreateBinary();

  xTaskCreate(mainTask, "mainTask", 256, NULL, PRIORITY_MEDIUM, NULL);

  xTaskCreate(stOpenBootTask, "stOpenBootTask", 256, NULL, PRIORITY_MEDIUM, NULL);

  /* Start scheduler */
  vTaskStartScheduler();

  while (1)
  {
    /* We should never get here as control is now taken by the scheduler */
  }
}
